import assert from "node:assert/strict";
import "../src/mocop/static/training_summary.js";

const { gpuSummary, runtimeSummary, submittedText } = globalThis.MocopTrainingSummary;
assert.equal(gpuSummary({ gpu_count: 8 }).text, "8 张");
assert.equal(gpuSummary({ gpu_count: 0 }).text, "0 张");
assert.equal(gpuSummary({ gpu_count: null, gpu_model: "Example GPU" }).note, "Example GPU");
assert.equal(gpuSummary({ name: "8GPU", replicas: { total: 8 } }).text, "未提供");
assert.equal(gpuSummary({ metrics_status: 200, metrics: { source: "provider", series: Array(8).fill({}) } }).text, "未提供");
const observed = { metrics_status: 200, metrics: { source: "stored", samples: [{ ts: 1, gpus: Array(8).fill({}) }, { ts: 2, gpus: Array(4).fill({}) }] } };
assert.equal(gpuSummary(observed).text, "4 张");
assert.equal(gpuSummary(observed).note, "观测 / 副本");
assert.equal(gpuSummary({ ...observed, metrics_status: 503 }).text, "未提供");
assert.equal(gpuSummary({ metrics_status: 200, metrics: { source: "stored", samples: [{ ts: 1, gpus: [] }] } }).text, "未提供");
assert.equal(runtimeSummary({ status: "RUNNING", created_at: 1000, started_at: 6000 }, 16000).text, "10秒");
assert.equal(runtimeSummary({ status: "RUNNING", created_at: 1000 }, 16000).note, "提交至今");
assert.equal(runtimeSummary({ status: "RUNNING", runtime_seconds: 5400 }, 16000).text, "1小时 30分");
assert.equal(runtimeSummary({ status: "RUNNING", runtime_seconds: 0 }, 16000).text, "0秒");
assert.equal(runtimeSummary({ status: "RUNNING", runtime_seconds: 0 }, 16000).note, "已运行");
assert.equal(runtimeSummary({ status: "FAILED", runtime_seconds: 10 }, 16000).text, "10秒");
assert.equal(runtimeSummary({ status: "RUNNING", runtime_seconds: -1 }, 16000).text, "未知");
assert.equal(runtimeSummary({ status: "PENDING", created_at: 1000, runtime_seconds: 0 }, 16000).note, "排队等待");
assert.equal(runtimeSummary({ status: "PENDING", created_at: 1000, started_at: 2000 }, 16000).note, "排队等待");
const done = { status: "SUCCEEDED", created_at: 1000, started_at: 6000, ended_at: 10000 };
assert.deepEqual(runtimeSummary(done, 16000), runtimeSummary(done, 999999));
assert.equal(runtimeSummary(done).text, "4秒");
assert.equal(runtimeSummary({ status: "FAILED", created_at: 1000 }).text, "未知");
assert.equal(runtimeSummary({ status: "RUNNING", started_at: 20000 }, 16000).text, "未知");
const replicas = { total: 2, complete: true, replicas: [{ started_at: 6000 }, { started_at: 8000 }] };
assert.equal(runtimeSummary({ status: "RUNNING", replicas_status: 200, replicas }, 16000).note, "副本开跑起");
assert.equal(runtimeSummary({ status: "RUNNING", replicas_status: 200, replicas }, 16000).text, "10秒");
assert.equal(runtimeSummary({ status: "RUNNING", replicas_status: 200, replicas: { ...replicas, complete: false } }, 16000).text, "未知");
assert.equal(runtimeSummary({ status: "RUNNING", replicas_status: 503, replicas }, 16000).text, "未知");
assert.equal(runtimeSummary({ status: "RUNNING", replicas_status: 200, replicas: { ...replicas, replicas: [{ started_at: 6000 }, { started_at: null }] } }, 16000).text, "未知");
assert.equal(submittedText(null), "未知");
assert.match(submittedText(1900000000000), /^2030-03-\d{2} \d{2}:\d{2}$/);
console.log("training summary contracts passed");

